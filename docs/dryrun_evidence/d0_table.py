"""Card 2 D0: d0_cells.json -> d0_cells.md (cell list). No data read."""
import json, sys
from collections import defaultdict
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
d = json.loads(src.read_text())
H2GB = {"ogbn-mag", "mag-year", "oag-cs", "oag-eng", "oag-chem", "ieee-cis-g", "h-pokec", "pdns"}
LARGE = {"ogbn-mag_pp", "h-pokec_uu"}
L = ["# Card 2 D0 — cell list", "", "Generated by `d0_cells.py` / `d0_table.py` (job 16741, see `d0_cells.txt`).", ""]
L += ["## H2S-NN cells (24)", "", "| task | dataset | config today | resolves | D0 class |", "|---|---|---|---|---|"]
for r in d["h2snn_cells"]:
    if r["dataset"] in LARGE:
        cls = "no H2S-NN entry point (LinkEpochLoop not wired to a dataset builder or trainer)"
    elif r["config_status"] == "resolves":
        cls = "ready (dry run D2)"
    else:
        cls = "config missing (D1)"
    src_ = r["config_source"] if r["config_source"].startswith("configs") else "preset only"
    L.append(f"| {r['task']} | {r['dataset']} | {src_} | {r['config_status']} | {cls} |")
by = defaultdict(list)
for r in d["baseline_cells"]:
    by[(r["task"], r["runnable"])].append(r)
L += ["", "## Baseline cells (registry `iter_cells`)", ""]
L.append(f"Total {len(d['baseline_cells'])}; runnable today {sum(r['runnable'] for r in d['baseline_cells'])}.")
L += ["", "### Runnable today (dry run D2)", "", "| task | dataset | models |", "|---|---|---|"]
grid = defaultdict(list)
for r in d["baseline_cells"]:
    if r["runnable"]:
        grid[(r["task"], r["dataset"])].append(r["model"])
for (t, ds), ms in grid.items():
    L.append(f"| {t} | {ds} | {', '.join(ms)} ({len(ms)}) |")
L += ["", "### Not runnable: H2GB NC and large LP (waiting for card 1b)", "", "| task | dataset | model | registry reason (first 120 chars) |", "|---|---|---|---|"]
other = []
for r in d["baseline_cells"]:
    if r["runnable"]:
        continue
    if r["dataset"] in H2GB or r["dataset"] in LARGE:
        tag = "N/A (author)" if r["reason"].startswith("N/A") else "waiting for card 1b"
        L.append(f"| {r['task']} | {r['dataset']} | {r['model']} | {tag}: {r['reason'][:120]} |")
    else:
        other.append(r)
L += ["", "### Not runnable elsewhere (no implementation / not wired)", "", "| task | dataset | model | reason (first 120 chars) |", "|---|---|---|---|"]
for r in other:
    L.append(f"| {r['task']} | {r['dataset']} | {r['model']} | {r['reason'][:120]} |")
out.write_text("\n".join(L) + "\n")
print(len(grid), "runnable (task, dataset) groups;", len(other), "other non-runnable")
