"""Card 17: the card 8 C1 rule for an H2GB published file, rebuilt (card 8 committed no generator).

    python ../docs/card17_evidence/gen_published.py check          # re-renders every existing H2GB file, byte-compare
    python ../docs/card17_evidence/gen_published.py write m:d ...  # writes configs/baselines/<m>/node_classification/<d>.yaml

Run from H2S-NN/. Rule: params = `yaml_published_values` (every key of the yaml minus EXCLUDED_KEYS, yacs-decoded, in
file order), lines = `yaml_key_lines` of those keys, source = the yaml path and the H2GB commit of vendor/VENDORS.tsv;
`yaml.safe_dump(sort_keys=False, width=120)`.
"""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, ".")
from src.baselines.h2gb_published import H2GB_PUBLISHED_CELLS, yaml_key_lines, yaml_published_values  # noqa: E402
from src.baselines.minibatch import h2gb_config_file  # noqa: E402
from src.baselines.published import published_params_path  # noqa: E402

COMMIT = next(line.split("\t")[2] for line in Path("vendor/VENDORS.tsv").read_text().splitlines()
              if line.startswith("H2GB\t"))
NOTES17 = ("Card 17 (author 2026-11-22, design-docs 54c241a option A): H2GB's published configuration, run exactly as "
           "the yaml states (H2GB's own model, loss and loss weights, optimizer, scheduler, clipping, accumulation, "
           "epochs, eval period, batch size, fan-out). Keys not transcribed (data, evaluation, logging) are listed in "
           "src/baselines/h2gb_published.py: EXCLUDED_KEYS. Generated by the C1 generator from the yaml "
           "(docs/card17_evidence/gen_published.py).")


def render(model: str, dataset: str, notes: str) -> str:
    path = h2gb_config_file(model, dataset)
    rel = "vendor/" + str(path).split("/vendor/", 1)[1]
    values = yaml_published_values(model, dataset)
    lines = yaml_key_lines(path)
    payload = {"model": model, "task": "node_classification", "dataset": dataset, "runner": "h2gb_yaml",
               "source": f"{rel} (H2GB commit {COMMIT}, vendor/VENDORS.tsv); the line of every value is under `lines:`",
               "notes": notes, "lines": {k: lines[k] for k in values}, "params": values}
    return yaml.safe_dump(payload, sort_keys=False, width=120, allow_unicode=True)


mode, cells = sys.argv[1], [c.split(":") for c in sys.argv[2:]]
if mode == "check":
    bad = checked = 0
    for model, dataset in sorted(H2GB_PUBLISHED_CELLS):
        p = published_params_path(model, "node_classification", dataset)
        if not p.exists():
            print(model, dataset, "absent")
            continue
        old = p.read_text(encoding="utf-8")
        same = render(model, dataset, yaml.safe_load(old)["notes"]) == old
        checked += 1
        bad += not same
        print(model, dataset, "IDENTICAL" if same else "DIFF")
    print(f"checked {checked}, differing {bad}")
    sys.exit(1 if bad else 0)
for model, dataset in cells:
    p = published_params_path(model, "node_classification", dataset)
    if p.exists():
        sys.exit(f"{p} exists")
    p.write_text(render(model, dataset, NOTES17), encoding="utf-8")
    values = yaml_published_values(model, dataset)
    lines = yaml_key_lines(h2gb_config_file(model, dataset))
    print("wrote", p, len(values), "keys")
